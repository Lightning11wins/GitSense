//! TypeScript bindings for the protocol, generated into the app's source tree.

use std::any::TypeId;
use std::collections::{BTreeMap, HashSet};

use ts_rs::{Config, TS, TypeVisitor};

use crate::Method;

pub trait MethodVisitor {
    fn visit<M: Method>(&mut self);
}

/// Returns a TypeScript module declaring every protocol type and a `Methods`
/// map from method name to its params and result types.
pub fn bindings() -> String {
    let cfg = Config::new().with_large_int("number");
    let mut collector = Collector { cfg: &cfg, seen: HashSet::new(), decls: BTreeMap::new(), methods: Vec::new() };
    collector.visit_type::<crate::HelperMessage>();
    crate::for_each_method(&mut collector);

    let mut out = String::from("// Generated by `cargo test -p gitsense-protocol`. Do not edit.\n\n");
    for decl in collector.decls.values() {
        out.push_str("export ");
        out.push_str(decl);
        out.push_str("\n\n");
    }
    out.push_str("export type Methods = {\n");
    for (name, params, result) in &collector.methods {
        out.push_str(&format!("  \"{name}\": {{ params: {params}; result: {result} }};\n"));
    }
    out.push_str("};\n");
    out
}

struct Collector<'a> {
    cfg: &'a Config,
    seen: HashSet<TypeId>,
    decls: BTreeMap<String, String>,
    methods: Vec<(&'static str, String, String)>,
}

impl Collector<'_> {
    fn visit_type<T: TS + 'static + ?Sized>(&mut self) {
        if !self.seen.insert(TypeId::of::<T>()) {
            return;
        }
        if T::output_path().is_some() {
            self.decls.insert(T::ident(self.cfg), T::decl(self.cfg));
        }
        T::visit_dependencies(self);
        T::visit_generics(self);
    }
}

impl TypeVisitor for Collector<'_> {
    fn visit<T: TS + 'static + ?Sized>(&mut self) {
        self.visit_type::<T>();
    }
}

impl MethodVisitor for Collector<'_> {
    fn visit<M: Method>(&mut self) {
        self.visit_type::<M::Params>();
        self.visit_type::<M::Result>();
        self.methods.push((M::NAME, M::Params::name(self.cfg), M::Result::name(self.cfg)));
    }
}

#[cfg(test)]
mod tests {
    /// Keeps the app's generated bindings in sync with the Rust types.
    #[test]
    fn write_bindings() {
        let path = concat!(env!("CARGO_MANIFEST_DIR"), "/../../app/src/protocol.gen.ts");
        let bindings = super::bindings();
        let current = std::fs::read_to_string(path).unwrap_or_default();
        if current != bindings {
            std::fs::write(path, &bindings).expect("Failed to write protocol bindings");
        }
    }
}
